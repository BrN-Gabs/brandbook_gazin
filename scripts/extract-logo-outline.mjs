// Extracts the outer silhouette of the blue Gazin frame from the original PNG
// (the project has no vector file) and writes it as an SVG path in image pixels.
// The frame is convex, so each ray from the centre crosses its edge exactly once:
// rays are marched inward from outside and refined to sub-pixel precision.
// Usage: node scripts/extract-logo-outline.mjs
import { readFile, writeFile } from 'node:fs/promises'
import { chromium } from '@playwright/test'

const png = await readFile(new URL('../public/assets/logo-gazin.png', import.meta.url))
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome' })
const page = await browser.newPage()
const result = await page.evaluate(async source => {
  const image = new Image()
  image.src = source
  await image.decode()
  const { naturalWidth: width, naturalHeight: height } = image
  const canvas = new OffscreenCanvas(width, height)
  const context = canvas.getContext('2d', { willReadFrequently: true })
  context.drawImage(image, 0, 0)
  const data = context.getImageData(0, 0, width, height).data
  // "Inside" = opaque and blue (the white letters are interior, never reached first).
  const inside = (x, y) => {
    const ix = Math.floor(x), iy = Math.floor(y)
    if (ix < 0 || iy < 0 || ix >= width || iy >= height) return 0
    const i = (iy * width + ix) * 4
    const alpha = data[i + 3] / 255
    const blue = data[i + 2] - Math.max(data[i], data[i + 1]) > 40 ? 1 : 0
    return alpha * blue
  }
  // Bilinear coverage gives a smooth, anti-aliased edge estimate.
  const coverage = (x, y) => {
    const x0 = Math.floor(x - .5), y0 = Math.floor(y - .5), fx = x - .5 - x0, fy = y - .5 - y0
    return inside(x0, y0) * (1 - fx) * (1 - fy) + inside(x0 + 1, y0) * fx * (1 - fy) + inside(x0, y0 + 1) * (1 - fx) * fy + inside(x0 + 1, y0 + 1) * fx * fy
  }
  const cx = width / 2, cy = height / 2
  const reach = Math.hypot(width, height)
  const samples = 6000
  const points = []
  for (let s = 0; s < samples; s++) {
    const angle = s / samples * Math.PI * 2
    const dx = Math.cos(angle), dy = Math.sin(angle)
    let outer = reach, step = 2, r = reach
    while (r > 0 && coverage(cx + dx * r, cy + dy * r) < .5) { outer = r; r -= step }
    let lo = r, hi = outer
    for (let k = 0; k < 24; k++) { const mid = (lo + hi) / 2; if (coverage(cx + dx * mid, cy + dy * mid) >= .5) lo = mid; else hi = mid }
    points.push([cx + dx * lo, cy + dy * lo])
  }
  return { width, height, points }
}, `data:image/png;base64,${png.toString('base64')}`)
await browser.close()

// Ramer–Douglas–Peucker on the closed loop (split at two far-apart points).
function simplify(points, tolerance) {
  const distance = ([px, py], [ax, ay], [bx, by]) => {
    const dx = bx - ax, dy = by - ay, length = Math.hypot(dx, dy) || 1
    return Math.abs(dy * px - dx * py + bx * ay - by * ax) / length
  }
  const run = (list) => {
    let max = 0, index = 0
    for (let i = 1; i < list.length - 1; i++) { const d = distance(list[i], list[0], list[list.length - 1]); if (d > max) { max = d; index = i } }
    if (max <= tolerance) return [list[0], list[list.length - 1]]
    return [...run(list.slice(0, index + 1)).slice(0, -1), ...run(list.slice(index))]
  }
  const half = Math.floor(points.length / 2)
  return [...run(points.slice(0, half + 1)).slice(0, -1), ...run([...points.slice(half), points[0]]).slice(0, -1)]
}
// Start at the top-left corner so the light's first lap reads naturally (clockwise on screen).
const simplified = simplify(result.points, .35)
let start = 0
simplified.forEach(([x, y], i) => { if (x + y * 3 < simplified[start][0] + simplified[start][1] * 3) start = i })
const ordered = [...simplified.slice(start), ...simplified.slice(0, start)]
const d = `M${ordered.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L')}Z`
await writeFile(new URL('../src/components/dna/logoOutline.ts', import.meta.url), `// Generated by scripts/extract-logo-outline.mjs from public/assets/logo-gazin.png.
// Outer silhouette of the blue Gazin frame, in the PNG's own pixel space.
export const logoSize = { width: ${result.width}, height: ${result.height} } as const
export const logoOutline = '${d}'
`)
console.log(`${result.points.length} samples -> ${ordered.length} points`)
