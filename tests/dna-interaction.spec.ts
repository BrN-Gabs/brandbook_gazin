import { test, expect } from '@playwright/test'

test.use({ viewport: { width: 1440, height: 900 }, reducedMotion: 'no-preference' })

test('Orientação base é reversível, mouse tem inércia e cena suspende fora da introdução', async ({ page }) => {
  await page.goto('/')
  const canvas = page.locator('.dna-canvas')
  await expect(canvas).toHaveAttribute('data-formation', '1.000')
  await expect(page.locator('.dna-loader')).toHaveCount(0)
  await page.mouse.move(1400, 450)
  await expect.poll(async () => Number(await canvas.getAttribute('data-pointer'))).toBeGreaterThan(.8)
  await page.mouse.move(40, 450)
  await expect.poll(async () => Number(await canvas.getAttribute('data-pointer'))).toBeLessThan(-.8)
  await page.locator('#dna-01').scrollIntoViewIfNeeded()
  await expect.poll(async () => Number(await canvas.getAttribute('data-turn'))).toBeGreaterThan(1)
  const turn = Number(await canvas.getAttribute('data-turn'))
  expect(turn).toBeGreaterThan(1)
  await page.locator('#dna-03').scrollIntoViewIfNeeded()
  await expect.poll(async () => Number(await canvas.getAttribute('data-turn'))).toBeGreaterThan(turn + 1)
  await page.locator('#dna-01').scrollIntoViewIfNeeded()
  await expect.poll(async () => Number(await canvas.getAttribute('data-turn'))).toBeCloseTo(turn, 2)
  await page.locator('#pilares').scrollIntoViewIfNeeded()
  await page.waitForTimeout(100)
  const frame = await canvas.getAttribute('data-frame')
  await page.waitForTimeout(200)
  expect(await canvas.getAttribute('data-frame')).toBe(frame)
  await page.locator('#dna-01').scrollIntoViewIfNeeded()
  await expect.poll(() => canvas.getAttribute('data-frame')).not.toBe(frame)
})

test('Movimento reduzido renderiza uma cena estática, sem loop contínuo', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  const canvas = page.locator('.dna-canvas')
  await expect(canvas).toHaveAttribute('data-formation', '1.000')
  await page.waitForTimeout(100)
  const frame = await canvas.getAttribute('data-frame')
  await page.mouse.move(1300, 450)
  await page.waitForTimeout(200)
  expect(await canvas.getAttribute('data-frame')).toBe(frame)
})
